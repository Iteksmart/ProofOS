"""PDF report generation for audits (reportlab)."""
from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.models.models import Audit, AuditFinding


def build_audit_pdf(audit: Audit, findings: list[AuditFinding], org_name: str, ai_summary: str | None = None) -> bytes:
    """Render an audit as a PDF and return its bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=letter, title=f"ProofOS {audit.kind} audit")
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("H1", parent=styles["Title"], fontSize=20, spaceAfter=6)
    h2 = ParagraphStyle("H2", parent=styles["Heading2"], fontSize=13, spaceBefore=10, spaceAfter=4)
    body = styles["BodyText"]

    story = []
    story.append(Paragraph(f"ProofOS Infrastructure Audit — {audit.kind.title()}", h1))
    story.append(Paragraph(f"Organization: {org_name}", body))
    story.append(Paragraph(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", body))
    story.append(Paragraph(f"Overall score: {audit.score}/100", h2))
    story.append(Spacer(1, 6))

    story.append(Paragraph("Executive Summary", h2))
    story.append(Paragraph(ai_summary or audit.summary, body))
    story.append(Spacer(1, 6))

    story.append(Paragraph("Findings", h2))
    rows = [["Category", "Severity", "Finding", "Detail"]]
    for f in findings:
        rows.append([f.category, f.severity, f.title, f.detail])
    table = Table(rows, colWidths=[80, 60, 180, 180])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
    ]))
    story.append(table)
    story.append(Spacer(1, 12))
    story.append(Paragraph("Generated by ProofOS. Findings are computed from live platform data; receipts are verifiable via GET /v1/proof/verify/{id}.", body))

    doc.build(story)
    return buf.getvalue()
